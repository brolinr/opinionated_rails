# frozen_string_literal: true

module OpinionatedRails
  # `kamal init` writes a fully commented-out deploy.yml, which is not deployable and loses data:
  # no RAILS_MASTER_KEY, no volume for SQLite, no Redis for Sidekiq. This builds a file that is
  # complete for the chosen stack; only the CHANGE_ME values (server, registry, host) are left to fill in.
  module KamalConfig
    PLACEHOLDER = "CHANGE_ME"

    def self.service_name(app_name) = app_name.to_s.tr("_", "-")

    def self.deploy_yml(app_name:, database:, stack:)
      service = service_name(app_name)
      volume = app_name.to_s
      sqlite = database == :sqlite3
      redis = stack == :redis

      lines = []
      lines << "# Kamal deployment for #{service}, generated by opinionated_rails."
      lines << "# Replace every #{PLACEHOLDER}_* value, then run `bin/kamal setup`. Docs: https://kamal-deploy.org"
      lines << "service: #{service}"
      lines << "image: #{PLACEHOLDER}_registry_username/#{service}"
      lines << ""
      lines << "servers:"
      lines << "  web:"
      lines << "    - #{PLACEHOLDER}_server_ip"
      if redis
        lines << "  job:"
        lines << "    hosts:"
        lines << "      - #{PLACEHOLDER}_server_ip"
        lines << "    cmd: bundle exec sidekiq"
      end
      lines << ""
      lines << "proxy:"
      lines << "  ssl: true"
      lines << "  host: #{PLACEHOLDER}.example.com"
      lines << ""
      lines << "registry:"
      lines << "  username: #{PLACEHOLDER}_registry_username"
      lines << "  password:"
      lines << "    - KAMAL_REGISTRY_PASSWORD"
      lines << ""
      lines << "builder:"
      lines << "  arch: amd64"
      lines << ""
      lines << "env:"
      lines << "  secret:"
      lines << "    - RAILS_MASTER_KEY"
      lines << "    - DATABASE_URL" unless sqlite
      lines << "  clear:"
      lines << (redis ? "    REDIS_URL: redis://#{service}-redis:6379/1" : "    SOLID_QUEUE_IN_PUMA: true")
      lines << ""
      lines << "# Persistent data. Without these, every deploy starts from an empty database/uploads."
      lines << "volumes:"
      lines << "  - \"#{volume}_storage:/rails/storage\""
      lines << "  - \"#{volume}_data:/data\"" if sqlite
      lines << ""
      lines << "# Keep old fingerprinted assets available to in-flight requests during a deploy."
      lines << "asset_path: /rails/public/assets"
      lines.concat(redis_accessory(service)) if redis
      lines << ""
      lines << "aliases:"
      lines << "  console: app exec --interactive --reuse \"bin/rails console\""
      lines << "  shell: app exec --interactive --reuse \"bash\""
      lines << "  logs: app logs -f"
      lines << "  dbc: app exec --interactive --reuse \"bin/rails dbconsole --include-password\""
      "#{lines.join("\n")}\n"
    end

    def self.redis_accessory(service)
      [
        "",
        "accessories:",
        "  redis:",
        "    image: redis:7",
        "    host: #{PLACEHOLDER}_server_ip",
        "    directories:",
        "      - data:/data",
        "    cmd: redis-server --appendonly yes"
      ]
    end

    # Safe to commit: values are read from the environment or from config/master.key, never written here.
    def self.secrets(database:)
      lines = [
        "# Read from your environment or a file; never write raw credentials here (this file is committed).",
        "KAMAL_REGISTRY_PASSWORD=$KAMAL_REGISTRY_PASSWORD",
        "RAILS_MASTER_KEY=$(cat config/master.key)"
      ]
      lines << "DATABASE_URL=$DATABASE_URL" unless database == :sqlite3
      "#{lines.join("\n")}\n"
    end
  end
end
